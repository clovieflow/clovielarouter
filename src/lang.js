let current = localStorage.getItem('clv_lang') || 'id';

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'id';
  localStorage.setItem('clv_lang', current);
  window.dispatchEvent(new Event('clv-lang-change'));
}

/**
 * Terjemahkan string. Sisipkan variable dengan {placeholder}:
 * t('ov.expiring', { n: 3, date: '14 Okt' })
 */
export function t(key, vars = {}) {
  const dict = translations[current] || translations.id;
  let str = dict[key] ?? translations.id[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, v);
  }
  return str;
}

/** Bahasa mana yang aktif sekarang — dipakai untuk toggle. */
export function isEnglish() {
  return current === 'en';
}
